"""Build the WebAssembly numeric kernels of the browser IndicXlit runtime.

The kernels (int8 GEMM, activation quantisation, GELU epilogue, layer norm, attention) are written in
AssemblyScript (a TypeScript dialect) in frontend/public/models/indicxlit/kernels/indicxlit-kernels.as.ts. This tool
compiles that file twice (with and without WebAssembly SIMD) and embeds the two binaries, base64-encoded, in
frontend/src/app/engine/hinglish/indicxlit-kernels.wasm.ts, so the runtime needs neither a bundler plugin nor a
network request for them. The compiler is a build-time tool only; nothing of it ships to visitors.

    cd backend
    .venv/Scripts/python.exe -m tools.export_indicxlit_kernels            # rebuild the embedded module
    .venv/Scripts/python.exe -m tools.export_indicxlit_kernels --check    # exit 1 when the embedded module is stale

Requires Node.js; AssemblyScript 0.28.2 is fetched with npx unless --asc points at an existing `asc`.
The output is deterministic: the same source and compiler give byte-identical binaries.
"""
import argparse
import base64
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ASC_VERSION = "0.28.2"
FLAGS = ["--optimize", "--noAssert", "--runtime", "stub", "--importMemory", "--initialMemory", "1"]
HEADER = "// GENERATED by backend/tools/export_indicxlit_kernels.py - do not edit.\n"


def compile_variant(asc, source, out, simd):
    command = list(asc) + [source.name, "--outFile", str(out)] + FLAGS + (["--enable", "simd"] if simd else [])
    done = subprocess.run(command, cwd=source.parent, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit(f"asc failed:\n{done.stdout}\n{done.stderr}")
    return out.read_bytes()


def render(source_path, simd, scalar):
    digest = hashlib.sha256(source_path.read_bytes()).hexdigest()
    return (
        HEADER
        + f"// source: public/models/indicxlit/kernels/{source_path.name} (sha256 {digest})\n"
        + f"// compiler: AssemblyScript {ASC_VERSION} {' '.join(FLAGS)} [--enable simd]\n"
        + f"// sizes: simd {len(simd)} bytes, portable {len(scalar)} bytes\n"
        + f"export const WASM_SIMD_BASE64 =\n  '{base64.b64encode(simd).decode()}';\n"
        + f"export const WASM_SCALAR_BASE64 =\n  '{base64.b64encode(scalar).decode()}';\n"
    )


def main():
    here = Path(__file__).resolve().parent.parent
    frontend = here.parent / "frontend"
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--source", type=Path, default=frontend / "public/models/indicxlit/kernels/indicxlit-kernels.as.ts")
    p.add_argument("--out", type=Path, default=frontend / "src/app/engine/hinglish/indicxlit-kernels.wasm.ts")
    p.add_argument("--asc", help="path of an existing asc executable (default: npx assemblyscript@%s)" % ASC_VERSION)
    p.add_argument("--check", action="store_true", help="do not write; fail if the embedded module differs")
    args = p.parse_args()
    if args.asc:
        asc = [args.asc]
    else:
        npx = shutil.which("npx")
        if not npx:
            sys.exit("Node.js (npx) is required to build the kernels")
        asc = [npx, "--yes", f"--package=assemblyscript@{ASC_VERSION}", "asc"]
    with tempfile.TemporaryDirectory(prefix="indicxlit-kernels-") as tmp:
        work = Path(tmp)
        source = work / args.source.name
        shutil.copyfile(args.source, source)
        simd = compile_variant(asc, source, work / "simd.wasm", True)
        scalar = compile_variant(asc, source, work / "scalar.wasm", False)
    text = render(args.source, simd, scalar)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        strip = lambda t: re.sub(r"// compiler:.*\n", "", t)  # the compiler line is informational
        if strip(current) != strip(text):
            sys.exit(f"{args.out} is stale: run python -m tools.export_indicxlit_kernels")
        print("embedded kernels are up to date")
        return
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} (simd {len(simd)} bytes, portable {len(scalar)} bytes)")
    provenance = args.source.parent.parent / "provenance.json"
    if provenance.is_file():  # record how the kernels were built next to the model they run
        info = json.loads(provenance.read_text(encoding="utf-8"))
        info["kernels"] = {
            "source": f"kernels/{args.source.name}",
            "source_sha256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
            "compiler": f"AssemblyScript {ASC_VERSION} " + " ".join(FLAGS) + " [--enable simd]",
            "embedded_in": "frontend/src/app/engine/hinglish/indicxlit-kernels.wasm.ts",
            "build": ".venv/Scripts/python.exe -m tools.export_indicxlit_kernels",
            "wasm_bytes": {"simd": len(simd), "portable": len(scalar)},
        }
        provenance.write_text(json.dumps(info, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
