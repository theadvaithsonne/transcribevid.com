// Generates golden.ts from the spike's Python reference outputs. Not part of the build (plain Node script).
//
//   node make-golden.mjs <vadScratchRoot>
//
// <vadScratchRoot>/data/ref holds, per clip variant, `<name>[.enh].json` (the segments that
// faster_whisper.vad.get_speech_timestamps returned for five parameter sets, collect_chunks metadata and the
// qwen_engine.chunks() output) and `<name>[.enh].probs.f32` (the per-frame probabilities of faster-whisper's
// silero_vad_v6.onnx, float32), plus `map.json` (SpeechTimestampsMap probes). All of them were produced by
// `py/ref_vad.py` / `py/ref_map.py` in the spike (docs/in-browser/spike/vad.md section 12) with faster-whisper
// 1.2.1 from backend/.venv. The 60 minute file is left out (1.1 MB); it is covered by the browser benchmark.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.argv[2];
if (!root) throw new Error('usage: node make-golden.mjs <vadScratchRoot>');
const ref = join(root, 'data', 'ref');
const here = dirname(fileURLToPath(import.meta.url));

const b64 = (buf) => {
  const s = Buffer.from(buf).toString('base64');
  const lines = [];
  for (let i = 0; i < s.length; i += 96) lines.push(`'${s.slice(i, i + 96)}'`);
  return lines.join(' +\n      ');
};

const variants = [];
for (const f of readdirSync(ref).sort()) {
  const m = /^(.*?)(\.enh)?\.json$/.exec(f);
  if (!m || f === 'map.json' || m[1] === 'long-60min') continue;
  const json = JSON.parse(readFileSync(join(ref, f), 'utf8'));
  const probs = readFileSync(join(ref, f.replace(/\.json$/, '.probs.f32')));
  if (probs.length !== json.frames * 4) throw new Error(`${f}: ${probs.length} bytes for ${json.frames} frames`);
  const configs = Object.fromEntries(
    Object.entries(json.configs).map(([k, c]) => [
      k,
      {
        segments: c.segments,
        ...(c.collect
          ? { collect: c.collect.map((x) => ({ offset: x.offset, duration: x.duration, segments: x.segments.length })) }
          : {}),
      },
    ]),
  );
  variants.push({ name: json.name, enh: !!json.enh, samples: json.samples, frames: json.frames, probs, configs,
    qwenChunks: json.qwenChunks, qwenChunksNoVad: json.qwenChunks_novad });
}

const map = JSON.parse(readFileSync(join(ref, 'map.json'), 'utf8')).map((c) => ({
  name: c.name,
  chunks: c.chunks,
  rows: c.rows.map((r) => [r.t, r.idx_start, r.idx_end, r.orig_start, r.orig_end]),
}));

let out = `// GENERATED by fixtures/make-golden.mjs from the spike's Python reference outputs - do not edit.
// faster-whisper 1.2.1 (backend/.venv): get_speech_timestamps, collect_chunks, SpeechTimestampsMap and
// backend/app/qwen_engine.chunks on the 26 spike clips, raw and after the engine's clean-up filter (enh).
// \`probs\` is the float32 probability trace of silero_vad_v6.onnx (little endian, base64), one value per
// 512-sample frame of the zero-padded stream; see docs/in-browser/spike/vad.md section 2 and 12.

export interface GoldenConfig {
  /** faster_whisper.vad.get_speech_timestamps result, [start, end) samples */
  segments: [number, number][];
  /** collect_chunks(max 30 s) metadata: offset / duration in seconds, number of listed segments */
  collect?: { offset: number; duration: number; segments: number }[];
}

export interface GoldenVariant {
  name: string;
  enh: boolean;
  samples: number;
  frames: number;
  probs: string;
  configs: Record<string, GoldenConfig>;
  /** qwen_engine.chunks(audio, 25, vad=True): [start, end, overlap] */
  qwenChunks: [number, number, boolean][];
  /** qwen_engine.chunks(audio, 25, vad=False) */
  qwenChunksNoVad: [number, number, boolean][];
}

export interface GoldenMapCase {
  name: string;
  chunks: [number, number][];
  /** [time on the speech-only timeline, chunk index (start rule), chunk index (end rule), original start, original end] */
  rows: [number, number, number, number, number][];
}

export const GOLDEN: GoldenVariant[] = [
`;
for (const v of variants) {
  out += `  {
    name: ${JSON.stringify(v.name)},
    enh: ${v.enh},
    samples: ${v.samples},
    frames: ${v.frames},
    probs:
      ${b64(v.probs)},
    configs: ${JSON.stringify(v.configs)},
    qwenChunks: ${JSON.stringify(v.qwenChunks)},
    qwenChunksNoVad: ${JSON.stringify(v.qwenChunksNoVad)},
  },
`;
}
out += `];

export const GOLDEN_MAP: GoldenMapCase[] = ${JSON.stringify(map)};
`;
writeFileSync(join(here, 'golden.ts'), out);
console.log(`${variants.length} variants, ${map.length} map cases, ${out.length} bytes`);
