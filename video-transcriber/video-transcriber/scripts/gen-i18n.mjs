#!/usr/bin/env node
/**
 * Writes frontend/src/app/i18n/generated.ts: which translations exist, as lazy loaders, so nothing is listed by hand.
 *
 *   node scripts/gen-i18n.mjs          (from video-transcriber/)
 *
 * Scans, per language code:
 *   i18n/dict/<code>.ts                                         the UI dictionary (default export) and, optionally,
 *                                                               `export const PAGES = ['/', '/faq', ...]`: the information
 *                                                               pages it covers completely (English paths)
 *   features/tool-pages/content/i18n/<code>/<slug>.ts           a translated tool page (export CONTENT)
 *   features/guides/content/i18n/<code>/<slug>.ts               a translated guide (export CONTENT)
 * A page is available in a language only when its text exists (an information page: when the dictionary lists it in PAGES).
 * Run it after adding or removing a translation and commit the result; i18n specs check the file is up to date.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..', 'frontend', 'src', 'app');
const LOCALES = ['es', 'pt', 'fr', 'de', 'it', 'id', 'ja', 'ko', 'th', 'vi', 'tr', 'hi', 'bn', 'ar', 'ur'];
const INFO_PAGES = ['/', '/how-it-works', '/faq', '/about', '/contact', '/privacy', '/terms', '/tools', '/guides'];

const list = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.endsWith('.spec.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort() : []);

const dicts = [];
const tools = {};
const guides = {};
const available = {};
for (const code of LOCALES) {
  const dictFile = path.join(app, 'i18n', 'dict', `${code}.ts`);
  const toolSlugs = list(path.join(app, 'features', 'tool-pages', 'content', 'i18n', code));
  const guideSlugs = list(path.join(app, 'features', 'guides', 'content', 'i18n', code));
  const pages = [];
  if (fs.existsSync(dictFile)) {
    dicts.push(code);
    const m = fs.readFileSync(dictFile, 'utf8').match(/export const PAGES\s*(?::[^=]+)?=\s*\[([\s\S]*?)\]/);
    for (const p of m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []) {
      if (!INFO_PAGES.includes(p)) throw new Error(`${code}: dict PAGES lists "${p}", which is not an information page`);
      pages.push(p);
    }
  }
  if (toolSlugs.length) tools[code] = toolSlugs;
  if (guideSlugs.length) guides[code] = guideSlugs;
  for (const s of toolSlugs) pages.push(`/${s}`);
  for (const s of guideSlugs) pages.push(`/guides/${s}`);
  // a language with pages but no dictionary would show English chrome: it gets no pages at all
  if (dicts.includes(code) && pages.length) available[code] = pages;
}

const q = (s) => `'${s}'`;
const lines = [];
lines.push(`// GENERATED by scripts/gen-i18n.mjs: do not edit. Run \`node scripts/gen-i18n.mjs\` after adding or removing a translation.`);
lines.push(`import { GuideContent } from '../features/guides/guide.model';`);
lines.push(`import { ToolPageContent } from '../features/tool-pages/tool-page.model';`);
lines.push(`import { Locale } from './locales';`);
lines.push('');
lines.push(`type Dict = Readonly<Record<string, string>>;`);
lines.push(`type Loader<T> = () => Promise<T>;`);
lines.push('');
lines.push('/** The UI dictionary of each language that has one (lazy). */');
lines.push(`export const DICT_LOADERS: Partial<Record<Locale, Loader<{ default: Dict }>>> = {`);
for (const c of dicts) lines.push(`  ${c}: () => import('./dict/${c}'),`);
lines.push('};');
lines.push('');
lines.push('/** The translated tool pages, by language and English slug (lazy). */');
lines.push(`export const TOOL_LOADERS: Partial<Record<Locale, Readonly<Record<string, Loader<{ CONTENT: ToolPageContent }>>>>> = {`);
for (const [c, slugs] of Object.entries(tools)) {
  lines.push(`  ${c}: {`);
  for (const s of slugs) lines.push(`    ${q(s)}: () => import('../features/tool-pages/content/i18n/${c}/${s}'),`);
  lines.push('  },');
}
lines.push('};');
lines.push('');
lines.push('/** The translated guides, by language and English slug (lazy). */');
lines.push(`export const GUIDE_LOADERS: Partial<Record<Locale, Readonly<Record<string, Loader<{ CONTENT: GuideContent }>>>>> = {`);
for (const [c, slugs] of Object.entries(guides)) {
  lines.push(`  ${c}: {`);
  for (const s of slugs) lines.push(`    ${q(s)}: () => import('../features/guides/content/i18n/${c}/${s}'),`);
  lines.push('  },');
}
lines.push('};');
lines.push('');
lines.push('/** The English paths that exist in each language. */');
lines.push(`export const AVAILABLE: Partial<Record<Locale, readonly string[]>> = {`);
for (const [c, pages] of Object.entries(available)) lines.push(`  ${c}: [${pages.map(q).join(', ')}],`);
lines.push('};');
lines.push('');
fs.writeFileSync(path.join(app, 'i18n', 'generated.ts'), lines.join('\n'));
console.log(`gen-i18n: ${Object.keys(available).length} language(s) with pages: ${Object.entries(available).map(([c, p]) => `${c} (${p.length})`).join(', ') || 'none yet'}`);
